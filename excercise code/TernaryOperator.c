#include<stdio.h>   //Ternary operator
int main()
{  int x=45;
  //ternary operator
  //it is similar to if else
  //it is used to reduce space 

   x >= 41 ? printf("pass") : printf("fail") ;
   //if this is true then first printf()will executed else second printf()
   x >= 90 ? printf("\nTopper") : printf("\nAverage") ;
   return 0;

}